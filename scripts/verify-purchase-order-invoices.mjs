// Isolated PostgreSQL verification. Uses the same PGlite installation as the
// existing lead-assignment database checks; no hosted records or email are used.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { PGlite } from "../tmp/lead-assignment-db/node_modules/@electric-sql/pglite/dist/index.js";
import { invoiceDocumentSchema, invoiceTotals } from "../lib/invoices.ts";
import { purchaseOrderAmounts } from "../lib/purchase-order-billing.ts";

const db = new PGlite();
const tenant = "11111111-1111-4111-8111-111111111111";
const other = "22222222-2222-4222-8222-222222222222";
const actor = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
const company = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";
const sql = (query, values = []) => db.query(query, values);
const row = async (query, values = []) => (await sql(query, values)).rows[0];
const migration = async name => db.exec(readFileSync(new URL(`../supabase/migrations/${name}.sql`, import.meta.url), "utf8"));
let checks = 0;
const equal = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
const rejects = async (work, pattern) => { await assert.rejects(work, pattern); checks++; };
try {
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls; create role crm_workspace_server;
    create schema auth;
    create table auth.users(id uuid primary key);
    create table workspace_members(user_id uuid,role text,activated_at timestamptz,display_name text);
    create table companies(id uuid primary key,name text,city text,country text);
    create table contacts(id uuid primary key,company_id uuid,email text);
    create table products(sku text primary key,currency text,moq integer,active boolean);
    create table events(id uuid default gen_random_uuid(),company_id uuid,actor_id uuid,type text,data jsonb,created_at timestamptz default now());
  `);
  for (const name of ["20261022093507_invoice_system", "20261023005013_connected_invoice_system", "20261023020501_invoice_creator_signature", "20261023084734_bd_manager_invoice_permissions", "20261026011039_company_purchase_orders", "20261026012617_connect_customer_orders_invoices", "20261029032328_purchase_order_product_connections"]) await migration(name);
  await db.exec(`create schema crm_tenancy;
    create function crm_tenancy.workspace_id() returns uuid language sql stable as $$ select nullif(current_setting('crm.workspace_id',true),'')::uuid; $$;
    grant usage on schema public,crm_tenancy to crm_workspace_server;
    grant execute on function crm_tenancy.workspace_id() to crm_workspace_server;
    select set_config('crm.workspace_id','${tenant}',false);
    insert into auth.users values('${actor}');
  `);
  for (const table of ["companies", "contacts", "products", "events", "workspace_members", "purchase_orders", "invoices", "invoice_payments", "invoice_events", "invoice_settings", "customer_billing_profiles"]) {
    await db.exec(`alter table ${table} add column workspace_id uuid not null default crm_tenancy.workspace_id();
      alter table ${table} enable row level security;
      create policy tenant on ${table} to crm_workspace_server using(workspace_id=crm_tenancy.workspace_id()) with check(workspace_id=crm_tenancy.workspace_id());
      grant select,insert,update,delete on ${table} to crm_workspace_server;`);
  }
  await db.exec(`alter table companies add unique(workspace_id,id);
    alter table purchase_orders drop constraint purchase_orders_company_id_fkey;
    alter table purchase_orders add foreign key(workspace_id,company_id) references companies(workspace_id,id);`);
  await db.exec("grant execute on all functions in schema public to crm_workspace_server; grant usage,select on all sequences in schema public to crm_workspace_server");
  await migration("20261106072947_purchase_order_serial_numbers");
  await db.exec(`set role crm_workspace_server;
    insert into workspace_members(user_id,role,activated_at,display_name) values('${actor}','admin',now(),'Test creator');
    insert into companies(id,name,city,country) values('${company}','Test buyer','Shanghai','China');
    insert into invoice_settings(settings) values('{"sellerName":"Test seller","sellerAddress":"Seller address","sellerTaxId":"TAX","paymentInstructions":"Bank transfer"}');
  `);
  const document = { reference: "", orderDate: "2026-11-06", deliveryDate: "", currency: "USD", status: "draft", paymentPolicy: "full_before_shipment", preShipmentPercent: 100, paymentTerms: "", shippingAddress: "Ship here", shippingRecipient: "Buyer", shippingPhone: "123", notes: "Order note", customer: { companyName: "Test buyer", contactName: "Buyer", contactRole: "", contactEmail: "buyer@example.test", billingEmail: "billing@example.test", billingAddress: "Bill here", taxId: "TAX-B", phone: "123" }, items: [{ description: "Product", sku: "CUSTOM", quantity: 3, unitPriceMinor: 1234 }, { description: "Shipping", sku: "SHIPPING", quantity: 1, unitPriceMinor: 550 }] };
  const create = async patch => {
    const doc = { ...document, ...patch };
    const total = purchaseOrderAmounts(doc).total;
    return row("insert into purchase_orders(company_id,reference,document,total_minor,created_by,updated_by) values($1,$2,$3,$4,$5,$5) returning *", [company, doc.reference, JSON.stringify(doc), total, actor]);
  };
  const update = async (order, patch) => {
    const doc = { ...order.document, ...patch };
    const total = purchaseOrderAmounts(doc).total;
    return row("update purchase_orders set document=$2,reference=$3,total_minor=$4,version=version+1 where id=$1 returning *", [order.id, JSON.stringify(doc), doc.reference, total]);
  };
  const invoiceFor = order => row("select * from invoices where purchase_order_id=$1 and status<>'void'", [order.id]);
  // A pre-existing manual allocation must retain its previous behavior.
  let legacy = await create({ status: "confirmed" });
  const legacyDoc = { companyId: company, purchaseOrderId: legacy.id, currency: "USD", reference: legacy.reference, items: legacy.document.items.map((item, index) => ({ ...item, purchaseOrderLineId: `line-${index + 1}`, taxBps: 0 })) };
  await sql("insert into invoices(document,total_minor,created_by) values($1,$2,$3)", [JSON.stringify(legacyDoc), legacy.total_minor, actor]);
  await db.exec("reset role");
  await migration("20261106084718_purchase_order_automatic_invoices");
  await migration("20261106091630_unified_order_invoice_numbers");
  await migration("20261106092917_purchase_order_billing_fields");
  await migration("20261106094241_remove_order_billing_extras");
  await db.exec("set role crm_workspace_server");
  let order = await create();
  let invoice = await invoiceFor(order);
  equal(invoice.status, "draft");
  equal(invoice.order_managed, true);
  equal(invoice.number, order.number);
  equal(invoice.document.reference, order.reference);
  equal(invoice.document.customerEmail, "billing@example.test");
  equal(invoice.document.sellerName, "Test seller");
  equal(invoice.creator_name, "Test creator");
  equal(invoice.total_minor, order.total_minor);
  equal(invoiceDocumentSchema.safeParse(invoice.document).success, true);
  const invoiceId = invoice.id;
  const oldRevision = invoice.revision;
  const adjusted = { ...invoice.document, discountMinor: 101, shippingMinor: 35, items: invoice.document.items.map(item => ({ ...item, taxBps: 725 })) };
  await sql("select mutate_invoice($1,$2,$3)", [invoice.id, actor, JSON.stringify({ action: "save", revision: invoice.revision, document: adjusted, totalMinor: invoiceTotals(adjusted).total })]);
  order = await update(order, { items: [{ ...document.items[0], quantity: 4 }, document.items[1]], customer: { ...document.customer, billingEmail: "new@example.test" }, shippingAddress: "New shipping" });
  invoice = await invoiceFor(order);
  equal(invoice.id, invoiceId);
  equal(invoice.document.items[0].quantity, 4);
  equal(invoice.document.customerEmail, "new@example.test");
  equal(invoice.document.shippingAddress, "New shipping");
  equal(invoice.document.discountMinor, 101);
  equal(invoice.total_minor, invoiceTotals(invoice.document).total);
  equal(invoice.revision, oldRevision + 2);
  await rejects(sql("select mutate_invoice($1,$2,$3)", [invoice.id, actor, JSON.stringify({ action: "save", revision: oldRevision, document: adjusted, totalMinor: 100 })]), /changed/);
  await rejects(sql("select mutate_invoice($1,$2,$3)", [invoice.id, actor, JSON.stringify({ action: "issue", revision: invoice.revision })]), /Confirm/);
  const reduced = { ...invoice.document, items: invoice.document.items.map((item, index) => index === 0 ? { ...item, quantity: 1 } : item) };
  await rejects(sql("select mutate_invoice($1,$2,$3)", [invoice.id, actor, JSON.stringify({ action: "save", revision: invoice.revision, document: reduced, totalMinor: invoiceTotals(reduced).total })]), /Edit products and quantities/);
  order = await update(order, { status: "confirmed" });
  equal((await invoiceFor(order)).id, invoiceId);
  equal((await row("select count(*)::int as n from invoices where purchase_order_id=$1", [order.id])).n, 1);
  await sql("select mutate_invoice($1,$2,$3)", [invoice.id, actor, JSON.stringify({ action: "issue", revision: invoice.revision })]);
  const issued = await invoiceFor(order);
  await rejects(update(order, { items: document.items }), /locked/);
  await rejects(update(order, { customer: document.customer }), /locked/);
  await rejects(update(order, { status: "cancelled" }), /Delete draft invoices or void/);
  await rejects(update(order, { status: "shipped" }), /payment/);
  order = await update(order, { notes: "New internal order note", shippingAddress: "Updated PO address" });
  equal((await invoiceFor(order)).document, issued.document);
  await sql("select mutate_invoice($1,$2,$3)", [issued.id, actor, JSON.stringify({ action: "void", revision: issued.revision })]);
  const replacement = await invoiceFor(order);
  equal(replacement.status, "draft");
  equal(replacement.number, order.number);
  equal(replacement.id === issued.id, false);
  equal((await row("select status from invoices where id=$1", [issued.id])).status, "void");
  const configuredBilling = { issueDate: "2026-11-06", dueDate: "2026-12-06", discountMinor: 101, taxBps: 725, paymentMethods: [] };
  let billedOrder = await create({ billing: { ...configuredBilling, sellerName: "Retired override", sellerAddress: "Retired", sellerTaxId: "Retired", paymentInstructions: "Retired", bankAccountId: "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa", bankAccount: {} } });
  const billedInvoice = await invoiceFor(billedOrder);
  equal(billedInvoice.total_minor, billedOrder.total_minor);
  equal(billedInvoice.total_minor, invoiceTotals(billedInvoice.document).total);
  for (const key of ["dueDate","discountMinor"]) equal(billedInvoice.document[key], configuredBilling[key]);
  for (const key of ["sellerName","sellerAddress","sellerTaxId","paymentInstructions","bankAccountId","bankAccount"]) equal(Object.hasOwn(billedOrder.document.billing,key),false);
  equal(billedInvoice.document.sellerName,"Test seller");
  equal(billedInvoice.document.paymentInstructions,"");
  equal(Object.hasOwn(billedInvoice.document,"bankAccountId"),false);
  equal(Object.hasOwn(billedInvoice.document,"bankAccount"),false);
  equal(billedInvoice.document.items[0].taxBps, 725);
  equal(billedInvoice.document.items[1].taxBps, 0);
  billedOrder = await update(billedOrder, { billing: { ...configuredBilling, discountMinor: 202 } });
  equal((await invoiceFor(billedOrder)).total_minor, billedOrder.total_minor);
  const cancellable = await create();
  await update(cancellable, { status: "cancelled" });
  equal(await invoiceFor(cancellable), undefined);
  await update({ ...cancellable, document: { ...cancellable.document, status: "cancelled" } }, { status: "draft" });
  equal((await invoiceFor(cancellable)).status, "draft");
  equal((await invoiceFor(cancellable)).number, cancellable.number);
  const count = (await row("select count(*)::int as n from purchase_orders")).n;
  await rejects(create({ items: [{ ...document.items[0], quantity: 1000000, unitPriceMinor: 100000000 }] }), /maximum|total/);
  equal((await row("select count(*)::int as n from purchase_orders")).n, count);
  await rejects(update(legacy, { items: [{ ...document.items[0], quantity: 8 }] }), /locked/);
  const converted = await create({ customer: undefined });
  equal((await invoiceFor(converted)).document.customerName, "Test buyer");
  equal(invoiceDocumentSchema.safeParse((await invoiceFor(converted)).document).success, true);
  equal((await row("select has_function_privilege('anon','public.sync_purchase_order_invoice()','execute') as allowed")).allowed, false);
  equal((await row("select has_function_privilege('authenticated','public.sync_purchase_order_invoice()','execute') as allowed")).allowed, false);
  await sql("select set_config('crm.workspace_id',$1,false)", [other]);
  equal((await row("select count(*)::int as n from invoices")).n, 0);
  await rejects(create(), /not found|foreign key|not-null|total|policy/i);
  console.log(`${checks} PostgreSQL assertions passed: atomic creation, synchronization, totals, stale revisions, cancellation, issuance, legacy allocations, and workspace isolation.`);
} finally { await db.close(); }
