/** Keep user-entered theme names intact while translating the surrounding controls. */
export function translatePortalThemeText(text: string): string | undefined {
  const patterns: [RegExp, (name: string) => string][] = [
    [/^More actions for (.+)$/, name => `${name} 的更多操作`],
    [/^Preview (.+) template$/, name => `预览 ${name} 模板`],
    [/^Preview (.+)$/, name => `预览 ${name}`],
    [/^Publish (.+)\?$/, name => `发布 ${name}？`],
    [/^Publish (.+)$/, name => `发布 ${name}`],
    [/^Remove (.+)\?$/, name => `移除 ${name}？`],
    [/^(.+) added as a draft\. Customize it when you’re ready\.$/, name => `${name} 已添加为草稿，您可以随时开始自定义。`],
    [/^(.+) is now published\.$/, name => `${name} 已发布。`],
  ];
  for (const [pattern, format] of patterns) { const match = text.match(pattern); if (match) return format(match[1]); }
}
